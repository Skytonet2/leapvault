/**
 * Compile Solidity contracts in contracts/src/*.sol with solc-js.
 *
 *   node scripts/compile-contracts.mjs
 *
 * Outputs artifact JSONs (ABI + bytecode) to contracts/artifacts/ and
 * regenerates lib/contracts/artifacts.ts so the rest of the app can import
 * ABIs as typed constants. Run after editing any .sol file.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const ROOT = join(fileURLToPath(import.meta.url), "..", "..");
const SRC = join(ROOT, "contracts", "src");
const OUT = join(ROOT, "contracts", "artifacts");
const TS_OUT = join(ROOT, "lib", "contracts", "artifacts.ts");

function loadSources() {
  const files = readdirSync(SRC).filter((f) => f.endsWith(".sol"));
  if (files.length === 0) throw new Error(`No .sol files in ${SRC}`);
  const sources = {};
  for (const file of files) {
    sources[file] = { content: readFileSync(join(SRC, file), "utf8") };
  }
  return sources;
}

function compile(sources) {
  const input = {
    language: "Solidity",
    sources,
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "paris",
      outputSelection: {
        "*": {
          "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "metadata"],
        },
      },
    },
  };

  const output = JSON.parse(solc.compile(JSON.stringify(input)));

  const errors = (output.errors || []).filter((e) => e.severity === "error");
  const warnings = (output.errors || []).filter((e) => e.severity !== "error");
  for (const w of warnings) console.warn(`[warn] ${w.formattedMessage}`);
  if (errors.length) {
    for (const e of errors) console.error(`[error] ${e.formattedMessage}`);
    throw new Error("Solidity compile failed");
  }
  return output;
}

function writeArtifacts(output) {
  if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });

  const tsLines = [
    "// AUTO-GENERATED by scripts/compile-contracts.mjs. Do not edit by hand.",
    'import type { Abi } from "viem";',
    "",
  ];

  for (const file of Object.keys(output.contracts)) {
    for (const name of Object.keys(output.contracts[file])) {
      const c = output.contracts[file][name];
      const artifact = {
        contractName: name,
        sourceFile: file,
        abi: c.abi,
        bytecode: `0x${c.evm.bytecode.object}`,
        deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
      };
      const outPath = join(OUT, `${name}.json`);
      writeFileSync(outPath, JSON.stringify(artifact, null, 2));
      console.log(`  ✓ ${basename(outPath)}`);

      tsLines.push(
        `export const ${name}Abi = ${JSON.stringify(c.abi)} as const satisfies Abi;`,
      );
      tsLines.push(
        `export const ${name}Bytecode = "0x${c.evm.bytecode.object}" as const;`,
      );
      tsLines.push("");
    }
  }

  writeFileSync(TS_OUT, tsLines.join("\n"));
  console.log(`  ✓ ${TS_OUT.replace(ROOT, "")}`);
}

function main() {
  console.log(`Compiling contracts in ${SRC}`);
  const sources = loadSources();
  const output = compile(sources);
  writeArtifacts(output);
  console.log("Compile complete.");
}

main();
